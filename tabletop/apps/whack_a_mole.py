"""Whack-a-mole on the table, in 2.5D.

    python -m tabletop.apps.whack_a_mole
    python -m tabletop.apps.whack_a_mole --difficulty advanced --skip-menu

Opens a start menu: pick a difficulty, or read the controls and the rules.
Fixed on-axis perspective; a mouse click stands in for a touch, and the
pointer is a mallet that follows the hand and swings when it strikes. The
rules live in :mod:`tabletop.game.whack_a_mole` and know nothing about
rendering, so they are unit-tested headlessly.

Where the depth comes from
--------------------------
With a *fixed* camera there is no head-motion parallax, so the sense of
depth has to come from cues that do not need a moving eye:

* **Tapered wells.** Real recessed geometry, sloped so the walls catch
  light. Straight cylinder walls are parallel to the view axis and nearly
  invisible from overhead.
* **Rim occlusion.** The hole geometry hides the mole's body while it is
  down. This is the cheapest and strongest depth cue available, and it needs
  no shader work — only real geometry.
* **Depth gradient.** Per-pixel darkening keyed to depth below the glass, so
  the bottom of a well recedes and a rising mole visibly brightens as it
  comes toward the player.
* **The mole's own Z travel.** Moving in Z changes its projected size and
  position, which is motion parallax generated by the object rather than by
  the viewer.

Press ``P`` for true viewer parallax: it switches to the off-axis frustum
driven by a nudgeable virtual viewpoint. Kept off the mouse deliberately —
the mouse is the finger here, and one pointer cannot be both the tap and
the viewpoint.

The frame around the playfield
------------------------------
The display is not all playfield. A thin raised bezel runs around the edge,
with a flat score band inside it carrying the scoreboard (see
:mod:`tabletop.core.layout`). Both are drawn as geometry on the glass plane
rather than as a screen-space overlay, for three reasons: they sit at known
millimetre positions on the panel, they behave correctly under head
parallax because they are part of the scene, and the headless capture
renders them -- UI-space elements do not appear in it at all.

Controls
--------
``left click``   swing the mallet
``P``            toggle head-parallax mode (off-axis frustum)
``arrows``       move the virtual head (only in parallax mode)
``D``            cycle difficulty (restarts the round)
``T``            cycle theme
``B``            cycle bezel finish (arcade / neon / ebony / tan)
``F``            cycle mole facing
``M``            cycle sprite mirroring
``R``            restart the round
``TAB``          back to the start menu
``ESC``          pause and ask what to do, as does tapping EXIT on the
                 score panel: resume, end the round, or leave the game
"""

