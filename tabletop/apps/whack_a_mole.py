MIRROR_MODES = ("random", "inward", "never", "always")
"""Whether the mole sprite is flipped horizontally.

The artwork's snout points right, so an unflipped mole on the right-hand
side of the table looks away from the table rather than across it. Mirroring
is a free fix -- a horizontal flip of a flat card costs nothing and the art
is not meaningfully asymmetric beyond its gaze.

``random``  follow the direction the rules drew for this mole at spawn
``inward``  flip moles on the right half so every mole faces the centre
``never``   leave the art as drawn (all face right)
``always``  flip every mole (all face left)

``random`` is the default and is the only mode whose direction comes from
the game rather than from geometry: ``HoleView.faces_right`` is drawn from
the seeded RNG when the mole spawns. Deciding it here instead would make a
frame's appearance depend on view state that no seed controls, so a replay
or a headless capture would not reproduce it.
"""

