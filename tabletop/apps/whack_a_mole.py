def mallet_owns_pointer(
    playing: bool, round_running: bool, pointer_on_field: bool
) -> bool:
    """Whether the mallet is the pointer, or the system cursor is.

    The mallet has the pointer while a round is running *and* the hand is
    over the playfield. Off the playfield the system cursor comes back, so
    the furniture around the field -- the exit button -- can be clicked with
    an ordinary cursor. Inside the field there is nothing to click but
    moles, and the mallet is the better pointer for that.

    Written as a function of state, not toggled at each transition, because
    a toggle has to be repeated on every path into a state and is silently
    wrong if one path is missed.
    """
    return playing and round_running and pointer_on_field


def _with_alpha(base, alpha: float) -> Vec4:
    """A colour at a given opacity. Vec4 avoids the 0-1 / 0-255 helpers."""
    return Vec4(base[0], base[1], base[2], clamp(alpha, 0.0, 1.0))


