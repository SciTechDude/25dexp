    def _build_effect_pool(self) -> None:
        """Fixed pools of entities for droplets and splats.

        Allocated once and recycled, never created per hit. Ursina entity
        construction touches the scene graph and compiles a mesh; doing that
        eleven times per whack, up to five whacks a second late in a round,
        is a visible hitch. The pool sizes come from the effect config's own
        caps, so the renderer cannot be handed more particles than it has
        entities for.
        """
        cfg = self.effects.config

        def pooled(radius_mm: float) -> Entity:
            return Entity(
                # Unit disc, scaled per particle: one mesh shape serves every
                # size, and scaling a flat disc cannot distort it.
                model=disc_mesh(radius_mm, segments=10),
                shader=UNLIT_120,
                enabled=False,
            )

        self.droplet_entities = [pooled(1.0) for _ in range(cfg.max_droplets)]
        self.splat_entities = [pooled(1.0) for _ in range(cfg.max_splats)]

