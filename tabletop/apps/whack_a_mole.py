MOLE_CARD_PITCH_FRACTION = 0.88
"""Mole sprite width, as a fraction of the grid pitch.

Derived from the layout rather than fixed in millimetres, so the art does
not need re-tuning when the frame is re-sized. A fixed width that no longer
matches the grid shows up twice over: cards wider than the pitch overlap
into one blob, and cards on the outer rows run off the field.

The fraction leaves a gap between neighbours while staying wider than the
80 mm hole, which the painted dirt mound has to cover.
"""

MOLE_CARD_TILT_DEG = 0.0
"""Tilt of the sprite away from flat. Zero: the card lies flat, facing the
overhead camera square-on.

Tilting was tried first, on the theory that a card standing up would read as
a body emerging rather than a sticker. It does not work here: the artwork is
drawn from eye level, so any tilt both foreshortens it and fights the
viewpoint, and every combination of rotation sign and vertical flip left the
mound above the head or the face pointing away. Flat is how front-facing art
is normally used in a top-down game -- the emergence is carried by the card
rising through the hole, with the ground occluding it on the way up, rather
than by its angle.
"""

