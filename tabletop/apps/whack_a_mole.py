    # -- scene ----------------------------------------------------------

    def _build_field(self) -> None:
        """Ground, as one hole-punched patch per grid cell.

        Not a single field quad: a solid quad at the glass plane is opaque
        and sits above the wells, so it occludes every hole interior and
        leaves only a sliver of rim visible. The ground genuinely has to
        have holes in it, so each cell contributes a patch with its hole cut
        out, and the patches tile the field exactly.
        """
        game = self.game
        cfg = game.config
        # A Mesh is a scene-graph node, not a shared asset: assigning one
        # instance to several Entities re-parents that single node, so only
        # one entity renders it. Each entity therefore gets its own mesh.
        field_texture = assets.load(assets.FIELD_TEXTURE, tile=True)
        self.field_textured = field_texture is not None

        def new_patch_mesh(hole):
            return field_patch_mesh(
                cell_width_mm=game.cell_width_mm,
                cell_height_mm=game.cell_height_mm,
                hole_radius_mm=cfg.hole_radius_mm,
                segments=18,
                centre_xy_mm=(hole.x_mm, hole.y_mm),
                # Whole-field UVs so the grass runs continuously across the
                # tiled patches instead of restarting at every cell.
                field_size_mm=(game.field_width_mm, game.field_height_mm),
                texture_repeat=FIELD_TEXTURE_REPEAT,
            )

        self.patches: list[Entity] = []
        for hole in game.holes():
            patch = Entity(
                model=new_patch_mesh(hole),
                texture=field_texture,
                position=Vec3(0, 0, 0),
                shader=LIT_120,
                double_sided=True,
            )
            # No depth gradient on the ground: it is all at z=0, so a
            # gradient would do nothing but dim it.
            apply_theme_to(
                patch,
                self.theme,
                "field",
                depth_gradient=0.0,
                textured=self.field_textured,
            )
            self.patches.append(patch)

    def _build_holes(self) -> None:
        cfg = self.game.config
        self.wells: list[Entity] = []
        self.moles: list[Entity] = []
        self.features: list[Entity] = []
        self.shadows: list[Entity] = []
        self.paws: list[list[Entity]] = []

        # Fresh mesh per entity -- see the note in _build_field.
        def new_well_mesh():
            return revolved_profile_mesh(
                well_profile(cfg.hole_radius_mm, cfg.hole_depth_mm),
                segments=18,
                # The visible surface is the *inside* of the shaft, so
                # normals must face the axis rather than away from it.
                orient_outward=False,
            )

        mole_sprite = assets.load(assets.MOLE_SPRITE)
        self.use_sprite = mole_sprite is not None
        gradient_span = mm_to_world(cfg.hole_depth_mm)
        self.card_width_mm = self._card_width_mm()

        for hole in self.game.holes():
            well = Entity(
                model=new_well_mesh(),
                position=Vec3(*table_to_world(hole.x_mm, hole.y_mm, 0.0)),
                shader=LIT_120,
                double_sided=True,
            )
            apply_theme_to(well, self.theme, "soil", depth_span_world=gradient_span)
            self.wells.append(well)

            if self.use_sprite:
                # A textured cutout card. The sprite already contains the
                # mole's head, paws and dirt mound, so none of the
                # procedural body, ears, snout or paws are needed -- and the
                # painted mound is what hides the seam where the card passes
                # through the hole.
                aspect = mole_sprite.height / mole_sprite.width
                card_height_mm = self.card_width_mm * aspect
                # Kept as the base for the impact squash. Reading the
                # entity's current scale back each frame would compound the
                # squash factor instead of applying it once.
                self._card_scale = (
                    mm_to_world(self.card_width_mm),
                    mm_to_world(card_height_mm),
                )
                # How much table-Z the tilted card spans, used to park it
                # fully below the hole floor when the mole is down.
                self._sprite_z_extent_mm = card_height_mm * math.sin(
                    math.radians(MOLE_CARD_TILT_DEG)
                )
                mole = Entity(
                    model="quad",
                    texture=mole_sprite,
                    scale=self._card_scale,
                    # Unlit: the artwork has its own shading baked in, and a
                    # directional term would fight it. Theme response comes
                    # from the colour tint instead.
                    shader=UNLIT_120,
                    double_sided=True,
                )
                apply_theme_to(mole, self.theme, "creature", textured=True)
            else:
                mole = Entity(
                    model=revolved_profile_mesh(
                        mole_profile(cfg.mole_radius_mm, cfg.mole_height_mm),
                        segments=14,
                        orient_outward=True,
                    ),
                    shader=LIT_120,
                )
                apply_theme_to(
                    mole, self.theme, "creature", depth_span_world=gradient_span
                )
            self.moles.append(mole)
            self.paws.append([])

            # The procedural body needs a cast shadow to read as above the
            # ground; the sprite already paints its own mound and contact
            # shading, where a second shadow just looks like a dark blob
            # sitting beside the mole.
            shadow = Entity(
                model=disc_mesh(cfg.mole_radius_mm * 1.05, segments=16),
                color=color.rgba32(0, 0, 0, 115),
                shader=UNLIT_120,
                enabled=not self.use_sprite,
            )
            self.shadows.append(shadow)

    def _card_width_mm(self) -> float:
        """Sprite width, scaled to the grid pitch so cards never overlap."""
        game = self.game
        pitch = min(game.cell_width_mm, game.cell_height_mm)
        return pitch * MOLE_CARD_PITCH_FRACTION

